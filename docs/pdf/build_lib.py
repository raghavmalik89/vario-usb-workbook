"""Shared ReportLab helpers for the Vario USB engineering report and paper.

Both documents are generated by scripts in this directory; this module
owns the common document scaffolding (styles, three-line tables, figure
helpers, formula rendering, header/footer).

Repro:
    python docs/pdf/build_engineering_report.py
    python docs/pdf/build_technical_paper.py
"""
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from reportlab.lib.colors import HexColor
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.platypus import (Image, Paragraph, Spacer, Table, TableStyle)

ROOT = Path(__file__).resolve().parents[2]
RESULTS = ROOT / "filter_benchmark" / "results"
FIGCACHE = Path(__file__).resolve().parent / "figs"
FIGCACHE.mkdir(exist_ok=True)

INK = HexColor("#333333")
ACCENT = HexColor("#1F3864")
GREY = HexColor("#666666")
LIGHT = HexColor("#f5f5f5")

BASE = getSampleStyleSheet()


def styles():
    s = {}
    s["title"] = ParagraphStyle(
        "TitleX", parent=BASE["Title"], fontName="Helvetica-Bold",
        fontSize=22, leading=28, textColor=ACCENT, spaceAfter=18)
    s["subtitle"] = ParagraphStyle(
        "SubtitleX", parent=BASE["Normal"], fontName="Helvetica",
        fontSize=13, leading=18, textColor=GREY, spaceAfter=6)
    s["h1"] = ParagraphStyle(
        "H1X", parent=BASE["Heading1"], fontName="Helvetica-Bold",
        fontSize=15, leading=19, textColor=ACCENT, spaceBefore=16,
        spaceAfter=8, keepWithNext=1)
    s["h2"] = ParagraphStyle(
        "H2X", parent=BASE["Heading2"], fontName="Helvetica-Bold",
        fontSize=12, leading=15, textColor=INK, spaceBefore=12,
        spaceAfter=5, keepWithNext=1)
    s["body"] = ParagraphStyle(
        "BodyX", parent=BASE["Normal"], fontName="Helvetica",
        fontSize=9.8, leading=14.2, textColor=INK, spaceAfter=6,
        alignment=4)  # justify
    s["caption"] = ParagraphStyle(
        "CaptionX", parent=BASE["Normal"], fontName="Helvetica-Oblique",
        fontSize=8.4, leading=11, textColor=GREY, spaceBefore=3,
        spaceAfter=10, alignment=1)
    s["tcell"] = ParagraphStyle(
        "TCellX", parent=BASE["Normal"], fontName="Helvetica",
        fontSize=8.6, leading=11.4, textColor=INK)
    s["tcell_c"] = ParagraphStyle(
        "TCellCX", parent=s["tcell"], alignment=1)
    s["ref"] = ParagraphStyle(
        "RefX", parent=BASE["Normal"], fontName="Helvetica", fontSize=9,
        leading=12.6, leftIndent=22, firstLineIndent=-22, textColor=INK,
        spaceAfter=3)
    s["code"] = ParagraphStyle(
        "CodeX", parent=BASE["Code"], fontName="Courier", fontSize=8,
        leading=10.5, textColor=INK, backColor=LIGHT,
        leftIndent=8, spaceBefore=4, spaceAfter=8)
    return s


def P(text, st):
    return Paragraph(text, st)


def three_line_table(header, rows, col_widths, center_cols=None,
                     font_size=8.6, header_fs=None):
    """Academic three-line table. header/rows are lists of str or Paragraph."""
    st = styles()["tcell"]
    stc = styles()["tcell_c"]
    center_cols = center_cols or set()
    hfs = header_fs or font_size

    def cell(x, col, hdr=False):
        sty = stc if col in center_cols else st
        if isinstance(x, Paragraph):
            return x
        return Paragraph(str(x), ParagraphStyle(
            "tmp", parent=sty, fontName="Helvetica-Bold" if hdr else "Helvetica",
            fontSize=hfs if hdr else font_size))

    data = [[cell(h, j, True) for j, h in enumerate(header)]]
    for r in rows:
        data.append([cell(c, j) for j, c in enumerate(r)])
    t = Table(data, colWidths=col_widths, repeatRows=1)
    t.setStyle(TableStyle([
        ("LINEABOVE", (0, 0), (-1, 0), 1.4, HexColor("#000000")),
        ("LINEBELOW", (0, 0), (-1, 0), 0.7, HexColor("#000000")),
        ("LINEBELOW", (0, -1), (-1, -1), 1.4, HexColor("#000000")),
        ("TOPPADDING", (0, 0), (-1, -1), 4.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4.5),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    return t


def figure(png_name, width_cm, caption, number, st):
    path = RESULTS / png_name
    if not path.exists():
        path = FIGCACHE / png_name
    from PIL import Image as PILImage
    with PILImage.open(path) as im:
        w_px, h_px = im.size
    w = width_cm * cm
    h = w * h_px / w_px
    img = Image(str(path), width=w, height=h)
    cap = P(f"<b>Figure {number}.</b> {caption}", st["caption"])
    return [img, cap]


def formula(name, tex, fontsize=13):
    """Render a mathtext formula to a transparent PNG, return Image flowable."""
    png = FIGCACHE / f"eq_{name}.png"
    if not png.exists():
        fig = plt.figure(figsize=(0.1, 0.1))
        t = fig.text(0, 0, f"${tex}$", fontsize=fontsize)
        fig.savefig(png, dpi=300, bbox_inches="tight",
                    pad_inches=0.05, transparent=True)
        plt.close(fig)
    from PIL import Image as PILImage
    with PILImage.open(png) as im:
        w_px, h_px = im.size
    target_w = min(12.5 * cm, w_px / 300 * cm * 2.2)
    return Image(str(png), width=target_w, height=target_w * h_px / w_px)


def header_footer(title):
    def _hf(canvas, doc):
        canvas.saveState()
        width, height = A4
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(GREY)
        canvas.drawString(2.5 * cm, height - 1.6 * cm, title)
        canvas.drawRightString(width - 2.5 * cm, height - 1.6 * cm,
                               "Vario USB workbook")
        canvas.setStrokeColor(HexColor("#bbbbbb"))
        canvas.setLineWidth(0.5)
        canvas.line(2.5 * cm, height - 1.8 * cm, width - 2.5 * cm, height - 1.8 * cm)
        canvas.drawCentredString(width / 2, 1.4 * cm, f"Page {doc.page}")
        canvas.restoreState()

    def _first(canvas, doc):
        canvas.saveState()
        width, _ = A4
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(GREY)
        canvas.drawCentredString(width / 2, 1.4 * cm, f"Page {doc.page}")
        canvas.restoreState()

    return _first, _hf


def spacer(h=6):
    return Spacer(1, h)
