"""02_validate_data.py — data quality & timestamp integrity (spec §2, §5).

Checks every recording for the failure modes that silently corrupt filter
comparisons: sequence gaps, out-of-order/duplicate timestamps, corrupt ADC
frames (the d1=0x000000 glitch class seen in t005_toss), IMU saturation,
error frames, rate variability, and sidecar/PROM coverage.

Writes:
  - reports/data_quality_report.md
  - results/data_quality_table.csv   (machine-readable, per run)
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))
from loader import data_files, rate_stats, sidecar_for  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT_MD = ROOT / "reports" / "data_quality_report.md"
OUT_CSV = ROOT / "results" / "data_quality_table.csv"

# Plausible raw-ADC bands for an MS5611 at bench altitude/temperature.
# Violations are the corrupt-read class (0x000000 / 0xFFFFFF / I2C garbage),
# NOT physics — real motion stays well inside these.
D1_BAND = (4_000_000, 12_000_000)
D2_BAND = (1_000_000, 16_000_000)


def validate_run(csv_path):
    df = pd.read_csv(csv_path)
    if "t_s" not in df:                      # raw CSVs carry t_us only
        df["t_s"] = df.t_us / 1e6
    sc = sidecar_for(csv_path)
    r = dict(file=csv_path.name)

    # --- sequence integrity (protocol seq is global, +1 per line) ----------
    seq = df.seq.values
    gaps = int(np.sum(np.diff(seq) != 1))
    r["seq_gaps"] = gaps
    r["seq_duplicates"] = int(len(seq) - len(np.unique(seq)))

    # --- timestamp monotonicity (physical sample time) ---------------------
    t = df.t_s.values
    r["out_of_order_t"] = int(np.sum(np.diff(t) < 0))
    r["duplicate_t"] = int(np.sum(np.diff(t) == 0))
    r["duration_s"] = round(float(t.max() - t.min()), 2) if len(t) else 0.0

    # --- per-channel checks --------------------------------------------------
    for ftype, band, col in (("P", D1_BAND, "d1"), ("T", D2_BAND, "d2")):
        grp = df[df.type == ftype]
        if grp.empty:
            continue
        vals = grp[col].dropna().values
        r[f"{ftype}_frames"] = len(vals)
        bad = int(np.sum((vals < band[0]) | (vals > band[1])))
        r[f"{ftype}_corrupt"] = bad
        for s in sorted(grp.sid.dropna().unique().astype(int)):
            sub = grp[grp.sid == s]
            st = rate_stats(sub.t_s.values)
            r[f"{ftype}_sid{s}_rate_hz"] = round(st["rate_hz"], 1) \
                if st["rate_hz"] == st["rate_hz"] else None
            r[f"{ftype}_sid{s}_p95_jitter_ms"] = round(st["p95_jitter_s"] * 1000, 3) \
                if st["p95_jitter_s"] == st["p95_jitter_s"] else None

    imu = df[df.type == "I"]
    if not imu.empty:
        cols = ["ax", "ay", "az", "gx", "gy", "gz"]
        sat = int(np.sum(np.abs(imu[cols].values) >= 32767))
        r["I_frames"] = len(imu)
        r["I_saturated"] = sat
        st = rate_stats(imu.t_s.values)
        r["I_rate_hz"] = round(st["rate_hz"], 1) if st["rate_hz"] == st["rate_hz"] else None

    e = df[df.type == "E"]
    r["E_frames"] = len(e)
    if len(e):
        # protocol E,<seq>,<t_us>,<code> — capture.py stores the code in
        # the 4th CSV field, i.e. the `sid` column
        r["E_codes"] = ";".join(f"code{int(c)}x{int(n)}" for c, n in
                                e.groupby("sid").size().items())

    # --- sidecar / PROM coverage ---------------------------------------------
    r["sidecar"] = sc is not None
    if sc:
        dev = sc.get("device", {})
        p_sids = sorted(df[df.type == "P"].sid.dropna().unique().astype(int))
        r["prom_missing_for"] = ";".join(f"sid{s}" for s in p_sids
                                         if f"prom_{s}" not in dev) or None
    return r


def verdict(row):
    if not row.get("sidecar"):
        return "EXCLUDED (no sidecar)"
    hard = (row.get("seq_gaps", 0) > 0 or row.get("out_of_order_t", 0) > 0
            or row.get("P_corrupt", 0) > 0 or row.get("T_corrupt", 0) > 0)
    if hard:
        return "usable with caveats (see report)"
    return "clean"


def main():
    rows = [validate_run(p) for p in data_files()]
    for r in rows:
        r["verdict"] = verdict(r)
    table = pd.DataFrame(rows).fillna("")
    OUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    table.to_csv(OUT_CSV, index=False)

    n_clean = sum(1 for r in rows if r["verdict"] == "clean")
    lines = ["# Data quality report — filter_benchmark Phase 1", "",
             "Generated by `scripts/02_validate_data.py`. Timestamp integrity "
             "is checked on per-frame `t_us` (physical sample time). Corrupt-frame "
             f"band: D1 outside {D1_BAND}, D2 outside {D2_BAND} (raw ADC counts).",
             "",
             f"Runs: {len(rows)} | clean: {n_clean} | with caveats/excluded: "
             f"{len(rows) - n_clean}", "",
             "| File | Dur [s] | seq gaps | o-o t | corrupt P | corrupt T | "
             "E frames | P rates [Hz] | verdict |",
             "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        rates = ", ".join(f"s{s}:{r.get(f'P_sid{s}_rate_hz')}" for s in (0, 1, 2)
                          if r.get(f"P_sid{s}_rate_hz") not in (None, ""))
        lines.append(f"| {r['file']} | {r.get('duration_s', '')} "
                     f"| {r.get('seq_gaps', '')} | {r.get('out_of_order_t', '')} "
                     f"| {r.get('P_corrupt', '')} | {r.get('T_corrupt', '')} "
                     f"| {r.get('E_frames', '')} | {rates} | {r['verdict']} |")
    flagged = [r for r in rows if r["verdict"] != "clean"]
    if flagged:
        lines += ["", "## Caveats (do not silently discard — spec §14)", ""]
        for r in flagged:
            bits = []
            if not r.get("sidecar"):
                bits.append("no sidecar: PROM missing, offline compensation "
                            "impossible; run excluded from filter comparisons")
            if r.get("seq_gaps"):
                bits.append(f"{r['seq_gaps']} sequence gaps (dropped samples)")
            if r.get("out_of_order_t"):
                bits.append(f"{r['out_of_order_t']} out-of-order timestamps")
            if r.get("P_corrupt"):
                bits.append(f"{r['P_corrupt']} corrupt P frame(s) "
                            f"(d1 outside plausible band — handled by the "
                            f"common.py sanity filter; root cause is a "
                            f"glitched I2C read, e.g. d1=0x000000)")
            if r.get("T_corrupt"):
                bits.append(f"{r['T_corrupt']} corrupt T frame(s)")
            if r.get("E_frames"):
                bits.append(f"{r['E_frames']} error frame(s): {r.get('E_codes', '?')}")
            lines.append(f"- **{r['file']}**: " + "; ".join(bits) + ".")
    lines += ["", "## Timestamp integrity statement",
              "",
              "Per-frame `t_us` comes from `esp_timer_get_time()` at the MCU "
              "when the sample is read. USB receipt time is not used anywhere in "
              "the benchmark. Duplicate `t_s` values arise when two sensors are "
              "read in the same lockstep tick (same physical instant), not from "
              "re-stamped data. Derivatives in later phases use these physical "
              "timestamps and measured (non-constant) intervals."]
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT_MD}")
    print(f"wrote {OUT_CSV}")
    print(f"{n_clean}/{len(rows)} runs clean")


if __name__ == "__main__":
    main()
