"""01_inventory.py — dataset discovery (task spec §2, step 1 of the mandate).

Scans analysis/data/, classifies every recording from its sidecar metadata,
measures actual sample rates from per-frame t_us (never assumed), and writes:
  - config/dataset_manifest.json   (machine-readable, drives later phases)
  - reports/dataset_inventory.md   (human-readable)
"""
import json
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))
from loader import classify, data_files, rate_stats, sidecar_for  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT_MD = ROOT / "reports" / "dataset_inventory.md"
OUT_JSON = ROOT / "config" / "dataset_manifest.json"


def inventory_run(csv_path):
    df = pd.read_csv(csv_path)
    if "t_s" not in df:                      # raw CSVs carry t_us only
        df["t_s"] = df.t_us / 1e6
    sc = sidecar_for(csv_path)
    label = csv_path.stem.split("_", 1)[1] if "_" in csv_path.stem else csv_path.stem
    rec = dict(
        file=csv_path.name,
        label=label,
        session_type=classify(label),
        rows=int(len(df)),
        duration_s=round(float(df.t_s.max() - df.t_s.min()), 2)
        if len(df) and "t_s" in df else None,
        channels={}, firmware=None, prom_sids=[], sidecar=sc is not None,
        notes=[],
    )
    if sc:
        dev = sc.get("device", {})
        fw = dev.get("firmware") or sc.get("firmware")
        if isinstance(fw, dict):
            fw = fw.get("name")
        rec["firmware"] = fw
        rec["prom_sids"] = sorted(int(k.split("_")[1])
                                  for k in dev if k.startswith("prom_"))
    for ftype, grp in df.groupby("type"):
        ch = dict(frames=int(len(grp)))
        sids = sorted(grp.sid.dropna().unique().astype(int).tolist()) \
            if "sid" in grp and grp.sid.notna().any() else []
        if sids:
            ch["sids"] = sids
        if ftype in ("P", "I") and len(grp) > 1:
            ch.update({k: round(v, 4) if v == v else None
                       for k, v in rate_stats(grp.t_s.values).items()})
        rec["channels"][ftype] = ch
    # evidence-limited statements only
    if not rec["sidecar"]:
        rec["notes"].append("NO SIDECAR — offline compensation impossible "
                            "(PROM missing); run is analysis-excluded until patched")
    else:
        p_sids = rec["channels"].get("P", {}).get("sids", [])
        missing = [s for s in p_sids if s not in rec["prom_sids"]]
        if missing:
            rec["notes"].append(f"sidecar lacks prom_{missing} — compensation "
                                f"will fail for those sids")
    if "I" not in rec["channels"]:
        rec["notes"].append("no IMU channel (baro-only run; fusion filters "
                            "Group F are NOT evaluable on this recording)")
    return rec


def main():
    runs = [inventory_run(p) for p in data_files()]
    manifest = dict(
        source_dir="analysis/data",
        protocol="docs/serial_protocol.md v1",
        timestamp_source="per-frame t_us from esp_timer_get_time() at the MCU "
                         "(physical sample time; USB receipt order not used)",
        reference_channels=dict(
            gps="UNAVAILABLE — no GPS in any recording",
            reference_vario="UNAVAILABLE — no reference vario output recorded",
            ground_truth_events="derived only: 1-s-smoothed baro crossings "
                                "(descriptive, NOT measured physical latency)",
        ),
        runs=runs,
    )
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps(manifest, indent=2))

    lines = ["# Dataset inventory — filter_benchmark Phase 1",
             "",
             "Generated by `scripts/01_inventory.py`. Session types come from "
             "capture labels (operator metadata) — they are naming, not "
             "independent evidence. Rates are measured from per-frame `t_us`, "
             "never assumed.",
             "",
             f"Total recordings: {len(runs)}", "",
             "| File | Session | Duration [s] | Rows | Baro sids (P rate) | "
             "IMU | Firmware | Notes |",
             "|---|---|---|---|---|---|---|---|"]
    for r in runs:
        p = r["channels"].get("P", {})
        baro = ", ".join(f"sid {s} ({p.get('rate_hz', '?')} Hz)" for s in p.get("sids", []))
        imu = f"{r['channels']['I'].get('rate_hz', '?')} Hz" if "I" in r["channels"] else "—"
        notes = "; ".join(r["notes"]) if r["notes"] else ""
        fw = (r["firmware"] or "?").replace("|", "/")
        lines.append(f"| {r['file']} | {r['session_type']} | {r['duration_s']} "
                     f"| {r['rows']} | {baro} | {imu} | {fw} | {notes} |")
    lines += ["", "## Reference-channel status (task spec §2.7)", "",
              "- **GPS:** Unavailable in all recordings.",
              "- **Reference vario output:** Unavailable in all recordings.",
              "- **Ground-truth events:** none independently recorded. All "
              "event timings in later phases derive from a smoothed barometric "
              "reference and are reported as descriptive comparisons only.",
              "", "## Known exclusions",
              "",
              "- Runs without a sidecar cannot be compensated offline and are "
              "excluded from filter comparisons until patched."]
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT_MD}")
    print(f"wrote {OUT_JSON}")
    print(f"{len(runs)} recordings inventoried; "
          f"{sum(1 for r in runs if not r['sidecar'])} missing sidecars; "
          f"{sum(1 for r in runs if 'I' in r['channels'])} with IMU")


if __name__ == "__main__":
    main()
